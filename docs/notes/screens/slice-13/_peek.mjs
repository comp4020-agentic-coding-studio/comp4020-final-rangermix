import { chromium } from "playwright";
const b = await chromium.launch(); const page = await (await b.newContext({ viewport: { width: 1920, height: 1080 } })).newPage();
await page.clock.install({ time: new Date("2026-11-04T10:00:00+11:00") }); await page.clock.resume();
await page.goto("http://localhost:8080");
await page.locator("#signup input[name=name]").fill(`p${Date.now().toString(36)}`);
await page.locator("#signup input[name=password]").fill("correct horse battery");
await page.locator("#signup button[type=submit]").click(); await page.locator("#code-done").click();
await page.waitForFunction(() => /inside/.test(document.getElementById("status-text")?.textContent ?? ""));
await page.waitForTimeout(800);
await page.locator("#room").screenshot({ path: process.argv[2] });
await b.close();
